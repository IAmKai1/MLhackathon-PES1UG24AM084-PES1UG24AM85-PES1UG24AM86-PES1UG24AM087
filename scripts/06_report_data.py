"""Collect every number the report needs into report/report_data.md, straight from the
result files (nothing typed by hand), and draw a static route-comparison figure.
"""
import json
import sys
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from pathsnap.hmm import HMMConfig  # noqa: E402
from pathsnap.pipeline import run_trip  # noqa: E402
from pathsnap.plotstyle import SERIES, plt, save  # noqa: E402

R = ROOT / "results"
OUT = ROOT / "report"
OUT.mkdir(exist_ok=True)


def md(df, floatfmt=4):
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: f"{v:.{floatfmt}f}")
    head = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(str(v) for v in r) + " |" for r in df.to_numpy()]
    return "\n".join([head, sep, *rows])


def route_figure(trip_id="00000077"):
    model = joblib.load(ROOT / "artifacts" / "final_model.joblib")
    cfg_raw = json.load(open(ROOT / "artifacts" / "hmm_config.json"))
    cfg = HMMConfig(**{k: cfg_raw[k] for k in HMMConfig().to_dict()})
    r = run_trip(ROOT / "data" / "student_test" / trip_id, model, cfg)
    trip, net = r["trip"], r["net"]
    fig, axes = plt.subplots(1, 2, figsize=(11, 5), sharex=True, sharey=True)
    for ax, key, title in [(axes[0], "classifier_arcs", "Classifier only"),
                           (axes[1], "hmm_arcs", "Classifier + HMM/Viterbi")]:
        for a in np.unique(trip.route):
            ax.plot(*np.c_[net.a[a], net.b[a]], color=SERIES[2], linewidth=4, alpha=0.35, solid_capstyle="round")
        arcs = r[key]
        for a in np.unique(arcs[arcs >= 0]):
            ax.plot(*np.c_[net.a[a], net.b[a]], color=SERIES[1], linewidth=1.6)
        ax.scatter(trip.xy[::3, 0], trip.xy[::3, 1], s=1.5, color=SERIES[0], linewidths=0)
        acc = r["score_classifier" if key == "classifier_arcs" else "score_hmm"]["observation_accuracy"]
        ax.set(title=f"{title}: accuracy {acc:.3f}", xlabel="x (m)")
        ax.set_aspect("equal")
    axes[0].set_ylabel("y (m)")
    axes[1].plot([], [], color=SERIES[2], linewidth=4, alpha=0.35, label="Reference route")
    axes[1].plot([], [], color=SERIES[1], label="Predicted arcs")
    axes[1].scatter([], [], s=8, color=SERIES[0], label="GPS")
    axes[1].legend(loc="lower right")
    fig.suptitle(f"Student-test trip {trip_id}: predicted arcs vs reference route", fontsize=11)
    save(fig, OUT / f"route_comparison_{trip_id}.png")


