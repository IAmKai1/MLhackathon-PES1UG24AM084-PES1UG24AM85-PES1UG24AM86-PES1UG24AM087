        "",
        "## 3.1 Overall model comparison",
        "",
        md(table, 4),
        "",
        "Additional per-model detail (CV = 5-fold GroupKFold on training trips; precision/recall on student-test):",
        "",
        md(detail, 4),
        "",
        "Per-fold CV macro F1:",
        "",
        md(fold_piv, 4),
        "",
        "## 4. Bayesian optimisation (HistGradientBoosting)",
        "",
        f"- Sampler: {best['sampler']}; CV: {best['cv']}; objective: {best['objective']}; trials: {best['n_trials']}",
        f"- Best CV macro F1: {best['best_cv_macro_f1']:.4f} (trial 0 = untuned defaults: {trials.value.iloc[0]:.4f})",
        "- Best parameters: " + ", ".join(f"{k}={v:.4g}" if isinstance(v, float) else f"{k}={v}"
                                          for k, v in best["best_params"].items()),
        "- Search space: learning_rate 0.02-0.3 (log), max_iter 100-600 (step 50), max_leaf_nodes 15-127,",
        "  min_samples_leaf 10-300 (log), l2_regularization 1e-6-10 (log), max_features 0.4-1.0",
        "",
